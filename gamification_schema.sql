-- 2. Create user_badges table
create table if not exists public.user_badges (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  achievement_id text references public.achievements(id) not null,
  unlocked_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(user_id, achievement_id) -- User can only unlock a specific badge once
);

-- Enable RLS
alter table public.user_badges enable row level security;

drop policy if exists "Users can view their own badges" on public.user_badges;
drop policy if exists "Users can view public badges" on public.user_badges;
drop policy if exists "Users can insert their own badges" on public.user_badges;

create policy "Users can view their own badges"
  on public.user_badges for select
  using ( auth.uid() = user_id );

-- For global leaderboards, people might need to see others' badges eventually, but for now we'll allow select for all (if needed) or just own.
create policy "Users can view public badges"
  on public.user_badges for select
  using ( true );

create policy "Users can insert their own badges"
  on public.user_badges for insert
  with check ( auth.uid() = user_id );
