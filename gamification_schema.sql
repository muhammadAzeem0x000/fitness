-- 1. Create achievements table (lookup table)
create table if not exists public.achievements (
  id text primary key,
  name text not null,
  description text not null,
  icon_name text not null,
  requirement_type text not null, -- 'volume', 'streak', 'workout_time', 'first_workout', etc.
  requirement_value numeric not null
);

-- Enable RLS (Read-only for all authenticated users)
alter table public.achievements enable row level security;
drop policy if exists "Users can view achievements" on public.achievements;
create policy "Users can view achievements"
  on public.achievements for select
  using ( true );

